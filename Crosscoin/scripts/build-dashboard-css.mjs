// Bundles the admin-only dashboard CSS into a single public/dashboard.css that
// is loaded ONLY on /dashboard routes (via a <link> in _app), instead of being
// baked into the global stylesheet that every storefront page downloads.
//
// Why: in the Next.js Pages Router, every `import "x.css"` in _app.jsx is merged
// into ONE render-blocking stylesheet served on EVERY page. ~226 KB of that was
// admin-page CSS (orders, whatsapp, pages, …) that shoppers never see — it was
// delaying First/Largest Contentful Paint on the storefront. Pulling it out of
// _app and loading it on demand removes that weight from the storefront's
// critical path while keeping the dashboard visually identical.
//
// Order matters (CSS cascade) — keep this list in the same order the imports
// had in _app.jsx. Runs automatically before `dev` and `build` (see package.json).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const stylesDir = join(root, 'src', 'styles', 'dashboard');
const outFile = join(root, 'public', 'dashboard.css');

// Admin-page CSS only. The shared UI kit (tokens, primitives, ui-*, dateRangePicker)
// stays global because storefront pages (Products/SearchResults) use Pagination/
// Modal from components/ui — do NOT move those here.
const FILES = [
  'dashboard-home.css',
  'manualOrder.css',
  'layout.css',
  'tables.css',
  'Card.css',
  'payments.css',
  'products.css',
  'orders.css',
  'media.css',
  'utmAnalytics.css',
  'attributes.css',
  'slider.css',
  'pages.css',
  'brands.css',
  'brandSettings.css',
  'brandTags.css',
  'brandAssignment.css',
  'seo.css',
  'social.css',
  'whatsapp.css',
  'analytics.css',
];

const parts = [];
let total = 0;
for (const name of FILES) {
  try {
    const css = readFileSync(join(stylesDir, name), 'utf8');
    parts.push(`/* ===== dashboard/${name} ===== */\n${css}`);
    total += css.length;
  } catch (e) {
    console.warn(`[build-dashboard-css] skipped missing ${name}: ${e.message}`);
  }
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `/* AUTO-GENERATED by scripts/build-dashboard-css.mjs — do not edit by hand.\n` +
  `   Edit the source files in src/styles/dashboard/*.css and rebuild. */\n\n` +
  parts.join('\n\n'),
);
console.log(`[build-dashboard-css] wrote ${outFile} (${FILES.length} files, ~${Math.round(total / 1024)}KB)`);
